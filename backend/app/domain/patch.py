"""
Patch domain models.

Defines the structured Search-and-Replace patch format that the AI engine
produces and the human reviewer approves.
"""

from datetime import datetime

# pyrefly: ignore [missing-import]
from pydantic import BaseModel, Field, field_validator


class PatchAction(BaseModel):
    """A single search-and-replace operation on a file."""

    file_path: str = Field(..., description="Relative path to the file within the repo")
    search_block: str = Field(..., description="Exact text block to search for (multi-line)")
    replace_block: str = Field(..., description="Replacement text block")
    explanation: str = Field(..., description="AI's reasoning for this change")

    @field_validator("search_block")
    @classmethod
    def search_must_not_be_empty(cls, v: str) -> str:
        """Search block cannot be empty — AI must specify what to replace."""
        if not v.strip():
            raise ValueError("search_block must not be empty or whitespace-only")
        return v

    @field_validator("file_path")
    @classmethod
    def file_path_must_not_be_empty(cls, v: str) -> str:
        """File path must be a valid non-empty string."""
        if not v.strip():
            raise ValueError("file_path must not be empty")
        return v


# Alias for explicit domain naming
PatchProposal = PatchAction


class PatchSet(BaseModel):
    """A complete set of patches generated by the AI for a single task."""

    task_id: str = Field(..., description="UUID of the parent task")
    actions: list[PatchAction] = Field(..., description="List of search-and-replace actions")
    summary: str = Field(..., description="AI-generated summary of all changes")

    @field_validator("actions")
    @classmethod
    def at_least_one_action(cls, v: list[PatchAction]) -> list[PatchAction]:
        """AI must propose at least one concrete change."""
        if len(v) == 0:
            raise ValueError("PatchSet must contain at least one PatchAction")
        return v


class PatchRecord(BaseModel):
    """Schema representing a patch row stored in Supabase."""

    id: str
    task_id: str
    file_path: str
    search_block: str
    replace_block: str
    explanation: str
    status: str = Field(..., description="pending | approved | rejected")
    created_at: datetime

